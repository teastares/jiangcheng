def building_function(ident):
    if ident in FUNCTIONS:
        return FUNCTIONS[ident]
    if 20 <= ident <= 24:
        return "固体物流", f"地面直行或转弯输送，额定 {BELT_SPEEDS[ident - 20] * 60} 件/分钟。"
    if 30 <= ident <= 34:
        index = ident - 30
        return "固体物流", f"成对架设同级地下带，需方向相对。额定 {BELT_SPEEDS[index] * 60} 件/分钟，端口间最大 {UNDERGROUND_SPANS[index]} 格。"
    if 400 <= ident <= 402:
        return "工坊防御", "用于区域分隔和工坊防线。"
    if 480 <= ident <= 483:
        return "照明", "为工坊提供光照。"
    if 501 <= ident <= 504:
        return "地板", "装饰性地板。"
    if 1101 <= ident <= 1103:
        return "家具", "可摆放的床。"
    if 1201 <= ident <= 1255:
        return "家具", "可摆放的家具或陈设。"
    if 1301 <= ident <= 1311:
        return "家具", "可摆放的座具。"
    if 1407 <= ident <= 1411:
        return "家具", "可交互的柜类家具。"
    if 1401 <= ident <= 1415:
        return "家具", "桌案或柜台，可摆放适用装饰。"
    if 1501 <= ident <= 1513:
        return "家具", "可摆放的挂饰或窗。"
    if 1701 <= ident <= 1714:
        return "家具", "可置于适用桌案上的陈设。"
    if 2101 <= ident <= 2306:
        return "景观", "装饰性树木、草丛、树桩或景观石。"
    return "待核对", "安装表有建筑记录，功能待核对。"


def device_catalog(database, unlocked=()):
    """按当前安装表整理设备，只有存档记录中的建筑才标为解锁。"""
    technologies = defaultdict(list)
    for ident, technology in database["technologies"].items():
        for building in technology["buildings"]:
            technologies[building].append((int(ident), technology["name"]))
    entries = {}
    for ident, building in database["buildings"].items():
        ident = int(ident)
        category, function = building_function(ident)
        status = ("支持" if ident in PLANNED else "部分支持" if ident in PARTIAL
                  else "不投用" if ident in CLOSED else "仅查阅")
        entries[ident] = {**building, "id": ident, "category": category, "function": function,
                          "status": status, "unlocked": ident in unlocked, "technologies": technologies[ident]}
    return entries
